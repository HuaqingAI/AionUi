type WorkspacePreparationLauncherOptions = {
  targetPath: string;
  nodeExecutable: string;
  nodeScript: boolean;
};

export function buildWorkspacePreparationLauncher({
  targetPath,
  nodeExecutable,
  nodeScript,
}: WorkspacePreparationLauncherOptions): string {
  return `// Generated by AionUi. Prepare assistant project files before starting the CLI.
'use strict';

const net = require('node:net');
const { spawn } = require('node:child_process');
const PREPARATION_TIMEOUT_MS = 40_000;
const MAX_MESSAGE_BYTES = 64 * 1024;
const targetPath = ${JSON.stringify(targetPath)};
const nodeExecutable = ${JSON.stringify(nodeExecutable)};
const nodeScript = ${JSON.stringify(nodeScript)};

function prepareWorkspace(conversationId, pipePath) {
  return new Promise((resolve) => {
    const request = JSON.stringify({
      token: process.env.AIONUI_WORKSPACE_PREPARATION_TOKEN || '',
      conversationId,
      workspace: process.cwd(),
    }) + '\\n';
    if (Buffer.byteLength(request, 'utf8') > MAX_MESSAGE_BYTES) {
      resolve('Workspace preparation request is too large.');
      return;
    }

    let socket;
    let response = Buffer.alloc(0);
    let settled = false;
    const timeout = setTimeout(() => finish('Workspace preparation timed out.'), PREPARATION_TIMEOUT_MS);

    function finish(error) {
      if (settled) return;
      settled = true;
      clearTimeout(timeout);
      if (socket) socket.destroy();
      resolve(error);
    }

    try {
      socket = net.createConnection(pipePath);
    } catch {
      finish('Workspace preparation connection failed.');
      return;
    }
    socket.once('connect', () => {
      if (settled) return;
      try {
        socket.write(request);
      } catch {
        finish('Workspace preparation connection failed.');
      }
    });
    socket.on('data', (chunk) => {
      if (settled) return;
      if (response.length + chunk.length > MAX_MESSAGE_BYTES) {
        finish('Workspace preparation response is too large.');
        return;
      }
      response = Buffer.concat([response, chunk]);
      const newline = response.indexOf(10);
      if (newline === -1) return;

      let message;
      try {
        message = JSON.parse(response.subarray(0, newline).toString('utf8'));
      } catch {
        finish('Workspace preparation returned an invalid response.');
        return;
      }
      if (!message || typeof message !== 'object' || Array.isArray(message) || typeof message.ok !== 'boolean') {
        finish('Workspace preparation returned an invalid response.');
        return;
      }
      finish(message.ok ? null : 'Workspace preparation was rejected.');
    });
    socket.once('error', () => finish('Workspace preparation connection failed.'));
    socket.once('end', () => finish('Workspace preparation disconnected.'));
    socket.once('close', () => finish('Workspace preparation disconnected.'));
  });
}

function startCommand() {
  const env = { ...process.env };
  for (const key of Object.keys(env)) {
    const name = process.platform === 'win32' ? key.toUpperCase() : key;
    if (name === 'AIONUI_WORKSPACE_PREPARATION_PIPE' || name === 'AIONUI_WORKSPACE_PREPARATION_TOKEN') delete env[key];
  }
  let child;
  try {
    child = spawn(nodeScript ? nodeExecutable : targetPath, nodeScript ? [targetPath, ...process.argv.slice(2)] : process.argv.slice(2), {
      shell: false,
      stdio: 'inherit',
      windowsHide: true,
      env,
    });
  } catch {
    process.stderr.write('Unable to start the configured CLI.\\n');
    process.exitCode = 1;
    return;
  }

  const signalHandlers = new Map();
  const signals = process.platform === 'win32' ? ['SIGINT', 'SIGTERM', 'SIGHUP', 'SIGBREAK'] : ['SIGINT', 'SIGTERM', 'SIGHUP'];
  for (const signal of signals) {
    const handler = () => {
      try {
        child.kill(signal);
      } catch {
        // The child may already have exited while the signal was being delivered.
      }
    };
    signalHandlers.set(signal, handler);
    process.on(signal, handler);
  }

  function removeSignalHandlers() {
    for (const [signal, handler] of signalHandlers) process.removeListener(signal, handler);
  }

  child.once('error', () => {
    removeSignalHandlers();
    process.stderr.write('Unable to start the configured CLI.\\n');
    process.exitCode = 1;
  });
  child.once('exit', (code, signal) => {
    removeSignalHandlers();
    if (signal) {
      try {
        process.kill(process.pid, signal);
      } catch {
        process.exitCode = 1;
      }
      return;
    }
    process.exitCode = code === null ? 1 : code;
  });
}

async function main() {
  const conversationId = process.env.AIONUI_CONVERSATION_ID;
  const pipePath = process.env.AIONUI_WORKSPACE_PREPARATION_PIPE;
  if (conversationId && pipePath) {
    const error = await prepareWorkspace(conversationId, pipePath);
    if (error) {
      process.stderr.write(error + '\\n');
      process.exitCode = 1;
      return;
    }
  }
  startCommand();
}

main().catch(() => {
  process.stderr.write('Workspace preparation failed.\\n');
  process.exitCode = 1;
});
`;
}
